import os
import typing
import pandas as pd

import torch.utils.data as torch_data

import lps_ml.core.loader as ml_loader
import lps_ml.core.processor as ml_proc
import lps_ml.core as ml_core
import lps_ml.datasets.selection as ml_sel

class Iemanja(ml_core.AudioDataModule):
    """
    DataModule for synthetic datasets generated by the Database.

    Expects the following structure:
        dataset_dir/
        ├── database.csv
        ├── ship_catalog.csv
        ├── acoutic_scenario_catalog.csv
        ├── dynamic_catalog.csv
        └── data/
            ├── 0.wav
            ├── 1.wav
            └── ...
    """

    @staticmethod
    def loader(data_base_dir: str) -> ml_core.AudioFileLoader:
        """ Get AudioFileLoader for Synthetical dataset. """
        import os

        return ml_core.AudioFileLoader(
            data_base_dir=data_base_dir,
            extract_id=lambda rel_path: int(
                os.path.splitext(os.path.basename(rel_path))[0]
            )
        )

    @staticmethod
    def load_df(dataset_dir: str) -> pd.DataFrame:

        database_csv = os.path.join(dataset_dir, "database.csv")
        ship_csv = os.path.join(dataset_dir, "ship_catalog.csv")
        scenario_csv = os.path.join(dataset_dir, "acoutic_scenario_catalog.csv")
        dynamic_csv = os.path.join(dataset_dir, "dynamic_catalog.csv")

        if not os.path.exists(database_csv):
            raise FileNotFoundError(database_csv)

        if not os.path.exists(ship_csv):
            raise FileNotFoundError(ship_csv)

        if not os.path.exists(scenario_csv):
            raise FileNotFoundError(scenario_csv)

        if not os.path.exists(dynamic_csv):
            raise FileNotFoundError(dynamic_csv)

        df_db = pd.read_csv(database_csv)
        df_ship = pd.read_csv(ship_csv)
        df_scen = pd.read_csv(scenario_csv)
        df_dyn = pd.read_csv(dynamic_csv)

        df_dyn = df_dyn.rename(columns={"CATALOG_ID": "DYNAMIC_CATALOG_ID"})
        df_db = df_db.merge(df_dyn, on="DYNAMIC_CATALOG_ID", how="left")

        df_scen = df_scen.rename(columns={"CATALOG_ID": "SCENARIO_CATALOG_ID"})
        df_db = df_db.merge(df_scen, on="SCENARIO_CATALOG_ID", how="left")

        df_ship = df_ship.rename(columns={"CATALOG_ID": "SHIP_CATALOG_ID"})
        df_db = df_db.merge(df_ship, on="SHIP_CATALOG_ID", how="left")

        return df_db

    @staticmethod
    def simple_selector() -> ml_sel.Selector:
        return ml_sel.Selector(
            target=ml_sel.CallbackTarget(
                n_targets=2,
                function=lambda row: 1 if row["CLASS"] == "Cargo" else 0
            ),
            filters=[
                ml_sel.ConstraintFilter(
                    constraints={"header": "DYNAMIC_TYPE", "value": ["fixed_distance"]},
                    remove_elements_in=False
                ),
                ml_sel.CallbackFilter(
                    lambda row: (row["CATALOG_ID"] % 4) < 2
                )
            ]
        )

    def __init__(self,
                 file_processor: ml_core.AudioProcessor,
                 processed_dir: str = "/data/Processed_data/iemanja",
                 dataset_dir: str = "/data/iemanja",
                 simple_version : bool = False,
                 batch_size: int = 32,
                 cv: ml_core.CrossValidator = None,
                 selection: ml_sel.Selector = None,
                 num_workers: int = None,
                 ):

        audio_dir = os.path.join(dataset_dir, "data")
        file_loader = Iemanja.loader(data_base_dir=audio_dir)

        df = Iemanja.load_df(dataset_dir)

        if simple_version:
            simple_selector = Iemanja.simple_selector()
            df = simple_selector.apply(df)

        if selection is not None:
            df = selection.apply(df)

        df["ID"] = df["CATALOG_ID"]
        if "Target" not in df.columns:
            df["Target"] = (df["CLASS"] == "Cargo").astype(int)


        super().__init__(
            file_loader=file_loader,
            file_processor=file_processor,
            description_df=df,
            processed_dir=processed_dir,
            batch_size=batch_size,
            num_workers=num_workers,
            cv=cv,
            transform=None,
        )

class IemanjaPaired(Iemanja):
    """
    DataModule for paired audio learning based on the Iemanja synthetic dataset.

    This class extends the standard Iemanja DataModule to support paired data
    loading. Pairing is defined at the file level using a user-provided `pair_builder`
    function, and then expanded to fragment-level pairs.

    The `pair_builder` function must operate on a metadata DataFrame
    and return a DataFrame with the following columns:

        - "file_id_1": Identifier of the source file
        - "file_id_2": Identifier of the target file

    Notes:
        - The pairing strategy can be customized by passing a different
          `pair_builder` function at initialization.
        - The default pairing strategy (`build_file_pairs_auto`) assumes that
          files sharing the same DYNAMIC_CATALOG_ID can be paired across
          different SCENARIO_CATALOG_ID values.
    """

    @staticmethod
    def build_file_pairs_auto(df_meta: pd.DataFrame) -> pd.DataFrame:
        """
        Default file-level pairing strategy for IemanjaPaired.

        This function generates pairs of file IDs based on the dataset metadata.
        It is intended to be used as the default `pair_builder` for the class.

        Pairing logic:
            - Groups samples by "DYNAMIC_CATALOG_ID", assuming same ship and dynamics.
            - Within each group, identifies distinct "SCENARIO_CATALOG_ID" values.
            - Selects the first two scenarios.
            - Pairs files from these two scenarios in a one-to-one fashion.

        The output defines directional pairs:
            file_id_1 → file_id_2

        Args:
            df_meta (pd.DataFrame):
                Metadata DataFrame containing at least the following columns:
                    - "ID" (or column defined by `id_column`)
                    - "DYNAMIC_CATALOG_ID"
                    - "SCENARIO_CATALOG_ID"

        Returns:
            pd.DataFrame:
                A DataFrame with the following columns:
                    - "file_id_1": Source file ID
                    - "file_id_2": Target file ID
        """

        pairs = []

        grouped = df_meta.groupby(["DYNAMIC_CATALOG_ID"])

        for _, group in grouped:

            scen_ids = group["SCENARIO_CATALOG_ID"].unique()

            if len(scen_ids) < 2:
                continue

            scen_a = scen_ids[0]
            scen_b = scen_ids[1]

            df_a = group[group["SCENARIO_CATALOG_ID"] == scen_a]
            df_b = group[group["SCENARIO_CATALOG_ID"] == scen_b]

            min_len = min(len(df_a), len(df_b))

            for k in range(min_len):
                pairs.append({
                    "file_id_1": df_a.iloc[k]["ID"],
                    "file_id_2": df_b.iloc[k]["ID"],
                })

        return pd.DataFrame(pairs)

    def __init__(self,
                 *args,
                 pair_builder: typing.Callable[[pd.DataFrame], pd.DataFrame] = None,
                 **kwargs):

        super().__init__(*args, **kwargs)

        self.pair_builder = pair_builder or self.build_file_pairs_auto

    def _expand_file_pairs_to_fragments(self,
                                        df_pairs: pd.DataFrame,
                                        df_frag: pd.DataFrame) -> pd.DataFrame:

        if df_pairs.empty:
            return df_pairs

        pairs = []

        grouped = df_frag.groupby("file_id")

        for _, row in df_pairs.iterrows():

            fid1 = row["file_id_1"]
            fid2 = row["file_id_2"]

            if fid1 not in grouped.groups or fid2 not in grouped.groups:
                continue

            df_a = grouped.get_group(fid1)
            df_b = grouped.get_group(fid2)

            min_len = min(len(df_a), len(df_b))

            for k in range(min_len):
                pairs.append({
                    "id_fragment_1": df_a.iloc[k]["id_fragment"],
                    "id_fragment_2": df_b.iloc[k]["id_fragment"],
                })

        return pd.DataFrame(pairs)

    def _build_dataloader(self,
                          df: pd.DataFrame,
                          shuffle: bool) -> torch_data.DataLoader:

        if df is None:
            raise RuntimeError("df is not initialized. Call setup() first.")

        file_ids = df["file_id"].unique()
        df_meta = self.description_df[
            self.description_df[self.id_column].isin(file_ids)
        ]

        file_pairs = self.pair_builder(df_meta)

        pairs_df = self._expand_file_pairs_to_fragments(file_pairs, df)

        return torch_data.DataLoader(
            ml_core.PairedProcessedDataset(
                pairs_df,
                self.processed_dir,
                self.transform
            ),
            batch_size=self.batch_size,
            shuffle=shuffle,
            num_workers=self.num_workers
        )

    def pairs_to_df(self) -> pd.DataFrame:

        df = self.dataframe

        file_ids = df["file_id"].unique()

        df_meta = self.description_df[
            self.description_df[self.id_column].isin(file_ids)
        ]

        file_pairs = self.pair_builder(df_meta)
        pairs_df = self._expand_file_pairs_to_fragments(file_pairs, df)

        if pairs_df.empty:
            return pairs_df

        base_df = self.dataframe

        df_input = base_df.add_prefix("input_")
        df_target = base_df.add_prefix("target_")

        merged = pairs_df.merge(
            df_input,
            left_on="id_fragment_1",
            right_on="input_id_fragment",
            how="left"
        )

        merged = merged.merge(
            df_target,
            left_on="id_fragment_2",
            right_on="target_id_fragment",
            how="left"
        )

        return merged
