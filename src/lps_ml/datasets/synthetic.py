class DynamicSelection(enum.Enum):
    ALL = enum.auto()
    FIXED_ONLY = enum.auto()
    MOBILE_ONLY = enum.auto()


class ChannelSelection(enum.Enum):
    ALL = enum.auto()
    REFERENCE_ONLY = enum.auto()
    NON_REFERENCE_ONLY = enum.auto()

class Iemanja(ml_core.AudioDataModule):
    """
    DataModule for synthetic datasets generated by the Database.

    Expects the following structure:
        dataset_dir/
        ├── database.csv
        ├── ship_catalog.csv
        ├── acoutic_scenario_catalog.csv
        ├── dynamic_catalog.csv
        └── data/
            ├── 0.wav
            ├── 1.wav
            └── ...
    """

    @staticmethod
    def loader(data_base_dir: str) -> ml_core.AudioFileLoader:
        """ Get AudioFileLoader for Synthetical dataset. """
        return ml_core.AudioFileLoader(
            data_base_dir=data_base_dir,
            extract_id=lambda rel_path: int(
                os.path.splitext(os.path.basename(rel_path))[0]
            )
        )

    @staticmethod
    def load_df(dataset_dir: str) -> pd.DataFrame:

        database_csv = os.path.join(dataset_dir, "database.csv")
        ship_csv = os.path.join(dataset_dir, "ship_catalog.csv")
        scenario_csv = os.path.join(dataset_dir, "acoutic_scenario_catalog.csv")
        dynamic_csv = os.path.join(dataset_dir, "dynamic_catalog.csv")

        if not os.path.exists(database_csv):
            raise FileNotFoundError(database_csv)

        if not os.path.exists(ship_csv):
            raise FileNotFoundError(ship_csv)

        if not os.path.exists(scenario_csv):
            raise FileNotFoundError(scenario_csv)

        if not os.path.exists(dynamic_csv):
            raise FileNotFoundError(dynamic_csv)

        df_db = pd.read_csv(database_csv)
        df_ship = pd.read_csv(ship_csv)
        df_scen = pd.read_csv(scenario_csv)
        df_dyn = pd.read_csv(dynamic_csv)

        df_dyn = df_dyn.rename(columns={"CATALOG_ID": "DYNAMIC_CATALOG_ID"})
        df_db = df_db.merge(df_dyn, on="DYNAMIC_CATALOG_ID", how="left")

        df_scen = df_scen.rename(columns={"CATALOG_ID": "SCENARIO_CATALOG_ID"})
        df_db = df_db.merge(df_scen, on="SCENARIO_CATALOG_ID", how="left")

        df_ship = df_ship.rename(columns={"CATALOG_ID": "SHIP_CATALOG_ID"})
        df_db = df_db.merge(df_ship, on="SHIP_CATALOG_ID", how="left")

        df_db["ID"] = df_db["CATALOG_ID"]
        return df_db

    @staticmethod
    def build_dynamic_filter(selection: DynamicSelection) -> typing.Optional[ml_sel.Filter]:

        if selection == DynamicSelection.ALL:
            return None
        elif selection == DynamicSelection.FIXED_ONLY:
            remove_elements_in = False
        elif selection == DynamicSelection.MOBILE_ONLY:
            remove_elements_in = True
        else:
            raise ValueError(
                f"Unsupported dynamic selection: {selection}"
            )

        return ml_sel.ConstraintFilter(
            constraints={
                "header": "DYNAMIC_TYPE",
                "value": ["fixed_distance"]
            },
            remove_elements_in = remove_elements_in
        )

    @staticmethod
    def build_channel_filter(selection: ChannelSelection) -> typing.Optional[ml_sel.Filter]:

        if selection == ChannelSelection.ALL:
            return None

        if selection == ChannelSelection.REFERENCE_ONLY:
            return ml_sel.CallbackFilter(
                lambda row: (row["CATALOG_ID"] % 4) < 2
            )

        if selection == ChannelSelection.NON_REFERENCE_ONLY:
            return ml_sel.CallbackFilter(
                lambda row: (row["CATALOG_ID"] % 4) >= 2
            )

        raise ValueError(
            f"Unsupported channel selection: {selection}"
        )

    @staticmethod
    def build_selector(
        dynamic_selection: DynamicSelection = DynamicSelection.ALL,
        channel_selection: ChannelSelection = ChannelSelection.ALL,
    ) -> ml_sel.MultiFilter:

        filters = []

        dynamic_filter = Iemanja.build_dynamic_filter(dynamic_selection)

        if dynamic_filter is not None:
            filters.append(dynamic_filter)

        channel_filter = Iemanja.build_channel_filter(channel_selection)

        if channel_filter is not None:
            filters.append(channel_filter)

        return ml_sel.MultiFilter(
            filters=filters
        )

    @staticmethod
    def build_column_as_target(target_column: str) -> ml_sel.Selector:
        target_column = target_column.upper()
        return ml_sel.Selector(ml_sel.CombinationTarget(columns=[target_column]))

    def __init__(self,
                 file_processor: ml_core.AudioProcessor,
                 processed_dir: str = "/data/Processed_data/iemanja",
                 dataset_dir: str = "/data/iemanja",

                 dynamic_selection: DynamicSelection = DynamicSelection.ALL,
                 channel_selection: ChannelSelection = ChannelSelection.ALL,

                 batch_size: int = 32,
                 cv: ml_core.CrossValidator = None,
                 selection: ml_sel.Selector = None,
                 num_workers: int = None,
                 group_column: str = "DYNAMIC_CATALOG_ID",
                 ):

        audio_dir = os.path.join(dataset_dir, "data")
        file_loader = Iemanja.loader(data_base_dir=audio_dir)

        df = Iemanja.load_df(dataset_dir)

        base_selector = Iemanja.build_selector(
            dynamic_selection=dynamic_selection,
            channel_selection=channel_selection
        )

        df = base_selector.apply(df)

        if selection is None:
            selection = Iemanja.build_column_as_target("CLASS")

        df = selection.apply(df)

        self.dynamic_selection = dynamic_selection
        self.channel_selection = channel_selection
        super().__init__(
            file_loader=file_loader,
            file_processor=file_processor,
            description_df=df,
            processed_dir=processed_dir,
            batch_size=batch_size,
            num_workers=num_workers,
            cv=cv,
            transform=None,
            group_column=group_column
        )

    def _get_params(self):
        params = super()._get_params()
        params.update({
            "dynamic_selection": self.dynamic_selection.name,
            "channel_selection": self.channel_selection.name,
        })
        return params

@ml_core.PairedAudioDataModule.register_pair_builder(Iemanja)
def iemenja_simple_file_pairs(df_meta: pd.DataFrame) -> pd.DataFrame:
    """
    Default file-level pairing strategy for Paired[Iemanja].

    This function generates pairs of file IDs based on the dataset metadata.
    It is intended to be used as the default `pair_builder` for the class.

    Pairing logic:
        - Groups samples by "DYNAMIC_CATALOG_ID", assuming same ship and dynamics.
        - Within each group, identifies distinct "SCENARIO_CATALOG_ID" values.
        - Selects the first two scenarios.
        - Pairs files from these two scenarios in a one-to-one fashion.

    The output defines directional pairs:
        file_id_1 → file_id_2

    Args:
        df_meta (pd.DataFrame):
            Metadata DataFrame containing at least the following columns:
                - "ID" (or column defined by `id_column`)
                - "DYNAMIC_CATALOG_ID"
                - "SCENARIO_CATALOG_ID"

    Returns:
        pd.DataFrame:
            A DataFrame with the following columns:
                - "file_id_1": Source file ID
                - "file_id_2": Target file ID
    """

    pairs = []

    grouped = df_meta.groupby(["DYNAMIC_CATALOG_ID"])

    for group_id, group in grouped:

        scen_ids = group["SCENARIO_CATALOG_ID"].unique()

        n_scenarios = len(scen_ids)
        if n_scenarios < 2:
              continue

        dfs = []
        n_frags = []
        for i in range(n_scenarios):
            dfs.append(group[group["SCENARIO_CATALOG_ID"] == scen_ids[i]])
            n_frags.append(len(dfs[-1]))

        for k in range(min(n_frags)):
              pairs.append({
                "DYNAMIC_CATALOG_ID": group_id[0],
                **{f"file_id_{i}": df.iloc[k]["ID"] for i, df in enumerate(dfs)}
              })

    return pd.DataFrame(pairs)

IemanjaPaired = ml_core.PairedAudioDataModule[Iemanja]

class IemanjaBuilder:

    def __init__(self, vae_exclusive = False, time_exclusive = False) -> None:
        self.vae_exclusive = vae_exclusive
        self.time_exclusive = time_exclusive

    def _add_dataset_args(self, parser: argparse.ArgumentParser):

        group = parser.add_argument_group(
            "Iemanja Dataset",
            "Dataset selection and labeling"
        )

        group.add_argument(
            "--ie-dataset-dir",
            type=str,
            default="/data/iemanja",
            help="Path to the raw dataset directory"
        )

        group.add_argument(
            "--ie-processed-dir",
            type=str,
            default="/data/Processed_data/iemanja",
            help="Path to the processed/cache directory"
        )

        group.add_argument(
            "--ie-dynamic-selection",
            type=str,
            default=DynamicSelection.ALL.name,
            choices=[e.name for e in DynamicSelection],
            help="Dynamic scenario selection"
        )

        group.add_argument(
            "--ie-channel-selection",
            type=str,
            default=ChannelSelection.ALL.name,
            choices=[e.name for e in ChannelSelection],
            help="Channel selection"
        )

        group.add_argument(
            "--ie-target",
            type=str,
            default="CLASS",
            help=(
                "Column used as label target. "
                "Examples: CLASS, CHANNEL, SHIP_TYPE."
            )
        )

        group.add_argument(
            "--ie-group-column",
            type=str,
            default="DYNAMIC_CATALOG_ID",
            help=(
                "Column used to separate cross-validation folds independently. "
                "Examples: SHIP_TYPE, SCENARIO_TYPE. If default, splits by DYNAMIC_CATALOG_ID."
            )
        )

        group.add_argument(
            "--ie-include-others",
            action="store_true",
            help="Create an additional target class for unmapped values."
        )

        group.add_argument("--ie-batch-size", type=int, default=32)
        group.add_argument("--ie-num-workers", type=int, default=1)

    def _add_processing_args(self, parser: argparse.ArgumentParser):

        group = parser.add_argument_group(
            "Iemanja Processing",
            "Audio preprocessing and feature extraction"
        )

        if not self.vae_exclusive and not self.time_exclusive:

            group.add_argument(
                "--ie-representation",
                type=str,
                default="raw",
                choices=[
                    "raw",
                    "spectral",
                    "latent",
                ],
                help="Input representation."
            )

        group.add_argument(
            "--ie-n-samples",
            type=int,
            default=2**17,
            help="Window size before representation conversion."
        )

        group.add_argument(
            "--ie-overlap",
            type=int,
            default=2**16,
            help="Window overlap before representation conversion."
        )

        if not self.time_exclusive:

            group.add_argument(
                "--ie-latent-model",
                type=str,
                default=None,
                help="Path to the latent encoder model."
            )

            group.add_argument(
                "--ie-latent-compactness",
                type=int,
                default=1024,
                help="Latent compression factor."
            )

        if not self.vae_exclusive and not self.time_exclusive:
            lps_analysis.SpectralAnalysis.add_args(parser=parser)

    def add_argparse_args(self, parser: argparse.ArgumentParser):
        self._add_dataset_args(parser)
        self._add_processing_args(parser)

    def _build_file_processor(self,
                             args: argparse.Namespace,
                             vae_model: str | None = None,
                             compactness: int = 1024) -> ml_core.AudioProcessor:

        n_samples = args.ie_n_samples
        overlap = args.ie_overlap

        pipelines : typing.List[ml_proc.AudioPipeline] = [
            ml_procs.ToFloatConverter()
        ]

        if not self.time_exclusive:

            if vae_model is not None:
                pipelines.append(ml_procs.VAEEncoder(vae_model))

                n_samples=int(n_samples / compactness)
                overlap=int(overlap / compactness)

            elif self.vae_exclusive or args.ie_representation == "latent":

                if args.ie_latent_model is None:

                    if self.vae_exclusive:
                        raise ValueError(
                            "--ie-latent-model must be provided "
                        )
                    else:
                        raise ValueError(
                            "--ie-latent-model must be provided "
                            "when --ie-representation latent"
                        )

                pipelines.append(ml_procs.VAEEncoder(args.ie_latent_model))

                n_samples=int(n_samples / args.ie_latent_compactness)
                overlap=int(overlap / args.ie_latent_compactness)

            elif args.ie_representation == "spectral":

                analysis, params = lps_analysis.SpectralAnalysis.build_from_args(args)

                pipelines.append(ml_procs.SpectralProcessor(analysis=analysis, params=params))

                n_samples=int(n_samples / params.n_spectral_pts)
                overlap=int(overlap / params.n_spectral_pts)

        return ml_procs.SampleProcessor(
            n_samples=n_samples,
            overlap=overlap,
            pipelines=pipelines
        )

    def _build_args(self,
                    args: argparse.Namespace,
                    vae_model: str | None = None,
                    compactness: int = 1024) -> dict:

        file_processor = self._build_file_processor(args=args,
                                                   vae_model=vae_model,
                                                   compactness=compactness)
        selection = Iemanja.build_column_as_target(target_column=args.ie_target)

        return dict(
            file_processor=file_processor,
            dataset_dir=args.ie_dataset_dir,
            processed_dir=args.ie_processed_dir,
            dynamic_selection=DynamicSelection[args.ie_dynamic_selection],
            channel_selection=ChannelSelection[args.ie_channel_selection],
            batch_size=args.ie_batch_size,
            cv=ml_core.SimpleSplitCV(stratify=False),
            selection=selection,
            num_workers=args.ie_num_workers,group_column=args.ie_group_column,
        )

    def from_argparse_args(self,
                           args: argparse.Namespace,
                           vae_model: str | None = None,
                           compactness: int = 1024) -> Iemanja:

        return Iemanja(
            **self._build_args(args=args, vae_model=vae_model, compactness=compactness)
        )

    def paired_from_argparse_args(self,
                                  args: argparse.Namespace,
                                  vae_model: str | None = None,
                                  compactness: int = 1024) -> IemanjaPaired:

        return IemanjaPaired(
            **self._build_args(args=args, vae_model=vae_model, compactness=compactness)
        )
